-- mod-dnd: per-character D&D sheet
CREATE TABLE IF NOT EXISTS `dnd_character` (
  `guid` INT UNSIGNED NOT NULL,
  `class` TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `str` TINYINT NOT NULL DEFAULT 8,
  `dex` TINYINT NOT NULL DEFAULT 14,
  `con` TINYINT NOT NULL DEFAULT 14,
  `intel` TINYINT NOT NULL DEFAULT 17,
  `wis` TINYINT NOT NULL DEFAULT 12,
  `cha` TINYINT NOT NULL DEFAULT 10,
  `slots_used` VARCHAR(64) NOT NULL DEFAULT '0,0,0,0,0,0,0,0,0',
  `temp_hp` INT NOT NULL DEFAULT 0,
  `short_rests_used` TINYINT NOT NULL DEFAULT 0,
  `arcane_recovery_used` TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (`guid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
